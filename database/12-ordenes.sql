CREATE TABLE IF NOT EXISTS ordenes (
  id INT AUTO_INCREMENT PRIMARY KEY,
  negocio_id INT NOT NULL,
  sucursal_id INT NOT NULL,
  numero_orden INT NOT NULL,
  codigo_seguimiento VARCHAR(36) NOT NULL,
  nombre_cliente VARCHAR(80) NOT NULL,
  tipo_entrega VARCHAR(10) NOT NULL,
  numero_mesa INT NULL,
  hora_recogida DATETIME NULL,
  metodo_pago VARCHAR(15) NOT NULL,
  estado_pago VARCHAR(10) NOT NULL DEFAULT 'SIN_PAGAR',
  estado VARCHAR(15) NOT NULL DEFAULT 'RECIBIDO',
  total DECIMAL(10,2) NOT NULL,
  motivo_cancelacion VARCHAR(255) NULL,
  iniciado_en DATETIME NULL,
  listo_en DATETIME NULL,
  entregado_en DATETIME NULL,
  creado_en TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_ordenes_negocio FOREIGN KEY (negocio_id) REFERENCES negocios(id),
  CONSTRAINT fk_ordenes_sucursal FOREIGN KEY (sucursal_id) REFERENCES sucursales(id),
  CONSTRAINT uq_ordenes_sucursal_numero UNIQUE (sucursal_id, numero_orden),
  CONSTRAINT uq_ordenes_codigo_seguimiento UNIQUE (codigo_seguimiento)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
